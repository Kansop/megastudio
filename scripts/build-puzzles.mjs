// Merges /tmp/pz*.json into js/apps/chess-puzzles.js (dedup, re-verified)
import fs from 'node:fs'; import { fromFEN, mateIn, uci, E } from './chess-lib.mjs';
const all = { 1: new Map(), 2: new Map(), 3: new Map() };
for (const f of fs.readdirSync('/tmp').filter((f) => /^pz\d+\.json$/.test(f))) { const d = JSON.parse(fs.readFileSync('/tmp/' + f)); for (const n of [1, 2, 3]) for (const [fen, sol] of d[n]) all[n].set(fen, sol); }
for (const [fen] of all[1]) if (!mateIn(fromFEN(fen), 1)) all[1].delete(fen);
for (const [fen] of all[2]) { const s = fromFEN(fen); if (mateIn(s, 1) || !mateIn(s, 2)) all[2].delete(fen); }
for (const [fen, sol] of all[3]) { const s = fromFEN(fen); if (mateIn(s, 2)) all[3].delete(fen); }
const out = { 1: [...all[1]], 2: [...all[2]], 3: [...all[3]] };
fs.writeFileSync('js/apps/chess-puzzles.js', '/* Mate puzzles generated by scripts/gen-puzzles.mjs (engine self-play + exhaustive mate verification) */\nMS.chessPuzzles = ' + JSON.stringify(out) + ';\n');
console.log(out[1].length, out[2].length, out[3].length);
